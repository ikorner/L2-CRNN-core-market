def main() -> None:
    idx = json.loads((ROOT / "review_index.json").read_text(encoding="utf-8"))
    assert len(idx) == 238, len(idx)
    fix_keys = {idx[i]: t for i, t in FIX.items()}
    skip_keys = [idx[i] for i in SKIP]
    overlap = set(fix_keys) & set(skip_keys)
    assert not overlap, f"пересечение FIX/SKIP: {overlap}"
    covered = set(FIX) | set(SKIP)
    auto = [i for i in range(len(idx)) if i not in covered]
    (ROOT / "fixups.json").write_text(
        json.dumps(fix_keys, ensure_ascii=False, indent=1), encoding="utf-8")
    (ROOT / "skips.json").write_text(
        json.dumps(skip_keys, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"FIX: {len(fix_keys)} ключей, SKIP: {len(skip_keys)} ключей, "
          f"на pred (conf>=0.95): {len(auto)} ключей")


if __name__ == "__main__":
    main()
